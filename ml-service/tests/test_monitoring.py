def test_dashboard_endpoint_active(client, isolate_prediction_logs):
    """Verify dashboard computes aggregations and score distributions from prediction logs."""
    secret = cfg.get_settings().INTERNAL_SERVICE_SECRET
    
    _write_mock_logs(isolate_prediction_logs, recency_avg=10.0, count_avg=1.0, n_records=30)
    
    response = client.get(
        "/api/v1/monitoring/dashboard",
        headers={"X-Internal-Secret": secret}
    )
    assert response.status_code == 200
    data = response.json()
    
    assert data["status"] == "active"
    assert data["total_predictions"] == 30
    assert len(data["recent_predictions"]) == 20  # Limit 20
    
    distributions = data["score_distributions"]
    assert distributions["avg_hybrid_score"] == 4.288
    assert distributions["avg_svd_score"] == 4.12
    assert distributions["avg_xgb_score"] == 4.54
    assert distributions["max_score"] == 4.288
    
    # Verify predictions_by_day holds counts grouped by date
    today_str = datetime.utcnow().strftime("%Y-%m-%d")
    assert today_str in data["predictions_by_day"]
    assert data["predictions_by_day"][today_str] == 30
