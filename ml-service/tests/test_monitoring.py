def _write_mock_logs(log_file_path, recency_avg, count_avg, n_records=50, stable=False):
    """Helper to populate mock prediction records."""
    now = datetime.utcnow()
    lines = []
    for i in range(n_records):
        if stable:
            # Match the exact baseline distributions generated by trainer.py on get_sample_data()
            interaction_count = 1
            user_role_encoded = 2
            project_member_count = 10
            recency_days = float(i % 30)  # ranges 0-29 just like the mock trainer interactions
        else:
            interaction_count = int(np.random.poisson(count_avg))
            user_role_encoded = int(np.random.choice([1, 2, 3], p=[0.2, 0.6, 0.2]))
            project_member_count = int(np.random.normal(10, 2))
            recency_days = float(np.random.normal(recency_avg, 2))

        log_entry = {
            "timestamp": (now - timedelta(minutes=i)).isoformat(),
            "model_version": "v1",
            "user_id": f"user_{i}",
            "project_id": f"project_{i}",
            "interaction_count": interaction_count,
            "user_role_encoded": user_role_encoded,
            "project_member_count": project_member_count,
            "recency_days": recency_days,
            "svd_score": 4.12,
            "xgb_score": 4.54,
            "hybrid_score": 4.288
        }
        lines.append(json.dumps(log_entry) + "\n")
        
    with open(log_file_path, "w") as f:
        f.writelines(lines)


def test_drift_endpoint_stable(client, isolate_prediction_logs):
    """Verify system is stable when logs match baseline training distributions."""
    secret = cfg.get_settings().INTERNAL_SERVICE_SECRET
    
    # Write mock logs with normal feature behaviors matching baseline exactly
    _write_mock_logs(isolate_prediction_logs, recency_avg=15.0, count_avg=1.0, stable=True)
    
    response = client.get(
        "/api/v1/monitoring/drift",
        headers={"X-Internal-Secret": secret}
    )
    assert response.status_code == 200
    data = response.json()
    
    assert data["status"] == "stable"
    assert data["sample_size"] == 50
    assert "recency_days" in data["metrics"]
    assert data["metrics"]["recency_days"]["status"] in ["stable", "moderate_drift"]


def test_drift_endpoint_drift_detected(client, isolate_prediction_logs, capsys):
    """Verify system flags drift and prints alert warning when feature values drift heavily."""
    secret = cfg.get_settings().INTERNAL_SERVICE_SECRET
    
    # Write mock logs with heavily drifted features
    # (e.g., recency averages 180 days, whereas training baseline average is around ~15 days)
    _write_mock_logs(isolate_prediction_logs, recency_avg=180.0, count_avg=0.1)
    
    response = client.get(
        "/api/v1/monitoring/drift",
        headers={"X-Internal-Secret": secret}
    )
    assert response.status_code == 200
    data = response.json()
    
    assert data["status"] == "drift_detected"
    assert data["metrics"]["recency_days"]["status"] == "significant_drift"
    assert data["metrics"]["recency_days"]["psi"] >= 0.2
    
    # Verify logger alert hook printed message to stdout
    captured = capsys.readouterr()
    assert "[CRITICAL ALERT]" in captured.out
    assert "recency_days" in captured.out


